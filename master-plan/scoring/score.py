"""Score the Compiled15 candidates and write RESULTS.md.

Usage: python3 master-plan/scoring/score.py [--config scores.yaml] [--runs 20000] [--seed 15]

The config may override the risk formula (`formula: {a, b}` for weighted * (a + b * p)),
enforce evidence (`evidence_rule: {min_score, cap}`: a criterion score >= min_score
without an `evidence` entry is capped), and set a qualification bar
(`qualify: {weighted_min, p_min}`). RESULTS.md is written next to the config.

Steps:
1. Drop candidates that fail a gate.
2. Weighted score (0-10) = sum(weight * score) / sum(weights).
3. Risk-adjusted score = weighted * (0.5 + 0.5 * p_success). A failed live demo
   still earns partial credit (recorded backup, code, pitch), so the penalty is capped at 50%.
4. Pick the best candidate per track by risk-adjusted score.
5. Sensitivity: Monte Carlo over random weights (Dirichlet around the base weights)
   and score noise (each score moved by -1, 0 or +1). Reports how often each
   candidate finishes first, and its mean rank.
"""

import argparse
import random
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent


def weighted(scores, weights):
    return sum(weights[c] * scores[c] for c in weights) / sum(weights.values())


def risk_adjusted(w, p, a=0.5, b=0.5):
    return w * (a + b * p)


def dirichlet(alphas, rng):
    draws = {k: rng.gammavariate(a, 1.0) for k, a in alphas.items()}
    total = sum(draws.values())
    return {k: v / total for k, v in draws.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=20000)
    ap.add_argument("--seed", type=int, default=15)
    ap.add_argument("--config", default=str(HERE / "scores.yaml"))
    args = ap.parse_args()

    config = Path(args.config).resolve()
    data = yaml.safe_load(config.read_text())
    fa, fb = data.get("formula", {}).get("a", 0.5), data.get("formula", {}).get("b", 0.5)
    ev_rule = data.get("evidence_rule")
    qualify = data.get("qualify")
    capped = []
    if ev_rule:
        for c in data["candidates"]:
            ev = c.get("evidence") or {}
            for k, sc in list(c["scores"].items()):
                if sc >= ev_rule["min_score"] and not ev.get(k):
                    c["scores"][k] = ev_rule["cap"]
                    capped.append(f"{c['name']}.{k} {sc}->{ev_rule['cap']}")
    crit = data["criteria"]
    weights = {k: v["weight"] for k, v in crit.items()}
    gates = list(data["gates"])
    tracks = data["tracks"]

    eligible, excluded = [], []
    for c in data["candidates"]:
        missing = [g for g in gates if g not in c["gates"]]
        (excluded if missing else eligible).append((c, missing))

    rows = []
    for c, _ in eligible:
        w = weighted(c["scores"], weights)
        rows.append({**c, "weighted": w, "risk_adj": risk_adjusted(w, c["p_success"], fa, fb)})
    rows.sort(key=lambda r: r["risk_adj"], reverse=True)

    winners = {}
    for r in rows:
        winners.setdefault(r["track"], r)
    finalists = sorted(winners.values(), key=lambda r: r["risk_adj"], reverse=True)

    # Monte Carlo sensitivity over finalists and over all eligible candidates.
    rng = random.Random(args.seed)
    alphas = {k: float(v) for k, v in weights.items()}  # concentration = 100 total

    def simulate(pool):
        wins = {r["id"]: 0 for r in pool}
        rank_sum = {r["id"]: 0 for r in pool}
        for _ in range(args.runs):
            wts = dirichlet(alphas, rng)
            sims = []
            for r in pool:
                noisy = {k: min(10, max(1, s + rng.choice((-1, 0, 1)))) for k, s in r["scores"].items()}
                sims.append((risk_adjusted(weighted(noisy, wts), r["p_success"], fa, fb), r["id"]))
            sims.sort(reverse=True)
            wins[sims[0][1]] += 1
            for i, (_, cid) in enumerate(sims, 1):
                rank_sum[cid] += i
        return ({k: v / args.runs for k, v in wins.items()},
                {k: v / args.runs for k, v in rank_sum.items()})

    fin_wins, fin_rank = simulate(finalists)
    all_wins, all_rank = simulate(rows)

    # Head-to-head margin between first and second finalist, per criterion.
    a, b = finalists[0], finalists[1]

    out = []
    out.append("# Scoring Results\n")
    out.append(f"Generated by `master-plan/scoring/score.py` from `{config.name}`. Do not edit by hand; re-run the script.\n")
    out.append(f"Risk formula: final = weighted x ({fa} + {fb} x p_success).\n")
    if ev_rule:
        out.append(f"Evidence rule: any criterion score >= {ev_rule['min_score']} without a cited `evidence` entry is capped at {ev_rule['cap']}. "
                   + (f"Capped this run: {', '.join(capped)}.\n" if capped else "Nothing was capped this run.\n"))
    if qualify:
        q = [r for r in rows if r["weighted"] >= qualify["weighted_min"] and r["p_success"] >= qualify["p_min"]]
        out.append(f"**Qualification bar:** weighted >= {qualify['weighted_min']} and p_success >= {qualify['p_min']}. "
                   f"Qualified: {', '.join(r['name'] for r in q) if q else 'none'}.\n")
    out.append(f"Monte Carlo runs: {args.runs}, seed {args.seed}. Weights resampled from Dirichlet(alpha = base weight), each score jittered by -1/0/+1.\n")

    out.append("## 1. Weights\n")
    out.append("| Code | Criterion | Weight |\n|---|---|---|")
    for k, v in crit.items():
        out.append(f"| {k} | {v['name']} | {v['weight']}% |")
    out.append("")

    out.append("## 2. All candidates (ranked by risk-adjusted score)\n")
    hdr = "| # | Track | Candidate | " + " | ".join(crit) + " | Weighted | p(success) | Final |"
    out.append(hdr)
    out.append("|" + "---|" * (len(crit) + 6))
    for i, r in enumerate(rows, 1):
        s = " | ".join(str(r["scores"][k]) for k in crit)
        out.append(f"| {i} | {r['track']} | {r['name']} | {s} | {r['weighted']:.2f} | {r['p_success']:.2f} | **{r['risk_adj']:.2f}** |")
    out.append("")
    if excluded:
        out.append("**Excluded by gates:** " + "; ".join(f"{c['name']} (fails {', '.join(m)})" for c, m in excluded) + "\n")

    out.append("## 3. Track winners\n")
    out.append("| Rank | Track | MVP | Weighted | Risk-adj | P(#1 of 6) | Mean rank of 6 |\n|---|---|---|---|---|---|---|")
    for i, r in enumerate(finalists, 1):
        out.append(f"| {i} | {r['track']}. {tracks[r['track']]} | **{r['name']}** | {r['weighted']:.2f} | {r['risk_adj']:.2f} | {fin_wins[r['id']]:.1%} | {fin_rank[r['id']]:.2f} |")
    out.append("")

    out.append("## 4. Sensitivity across all eligible candidates\n")
    out.append("| Candidate | P(#1 overall) | Mean rank |\n|---|---|---|")
    for r in sorted(rows, key=lambda r: all_rank[r["id"]]):
        out.append(f"| {r['name']} | {all_wins[r['id']]:.1%} | {all_rank[r['id']]:.2f} |")
    out.append("")

    out.append(f"## 5. Head-to-head: {a['name']} vs {b['name']}\n")
    out.append("| Criterion | Weight | " + a["name"] + " | " + b["name"] + " | Weighted margin |\n|---|---|---|---|---|")
    total = 0.0
    for k, v in crit.items():
        m = v["weight"] * (a["scores"][k] - b["scores"][k]) / sum(weights.values())
        total += m
        out.append(f"| {v['name']} | {v['weight']}% | {a['scores'][k]} | {b['scores'][k]} | {m:+.2f} |")
    out.append(f"| **Total** | | | | **{total:+.2f}** |\n")

    out.append("## 6. Break-even check\n")
    gap = a["risk_adj"] - b["risk_adj"]
    out.append(f"{a['name']} leads {b['name']} by {gap:.2f} risk-adjusted points. "
               f"{a['name']} would lose first place if its p(success) fell below "
               f"{max(0.0, (b['risk_adj'] / a['weighted'] - fa) / fb):.2f} (now {a['p_success']:.2f}), "
               f"or if {b['name']}'s p(success) rose above "
               f"{min(1.0, (a['risk_adj'] / b['weighted'] - fa) / fb):.2f} (now {b['p_success']:.2f}).\n")

    (config.parent / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
